/* =========================================================================
 * pat.js —— 地图图块图素（架构角色 ≈ 经典引擎的 PAT.MKF）
 *
 * 经典引擎把瓦片位图打包在 PAT.MKF 中；复刻版不搬运任何原版素材，
 * 而是用代码在启动时程序化绘制一套全新的 16×16 像素图块。
 * 网格字符含义见每个图块的调色板。
 * ========================================================================= */
"use strict";

const TILE = 16;                       // 瓦片像素尺寸
const Pat = { tiles: {}, anims: {} };  // tiles[name]=离屏canvas

function patCanvas(name, w, h) {
  const c = document.createElement("canvas");
  c.width = w || TILE; c.height = h || TILE;
  Pat.tiles[name] = c;
  return c.getContext("2d");
}

/* 像素网格工具：rows 为字符串数组，字符查 pal 调色板 */
function patPixels(name, rows, pal) {
  const g = patCanvas(name, rows[0].length, rows.length);
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const col = pal[row[x]];
      if (col) { g.fillStyle = col; g.fillRect(x, y, 1, 1); }
    }
  });
}

